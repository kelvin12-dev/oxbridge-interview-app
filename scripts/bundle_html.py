#!/usr/bin/env python3
"""
Bundle web/index.html and web/questions.js into a single self-contained
TypeScript module src/htmlBundle.ts for react-native-webview.
"""

import json
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
WEB_DIR = BASE_DIR / "web"
OUT_PATH = BASE_DIR / "src" / "htmlBundle.ts"


def main():
    html = (WEB_DIR / "index.html").read_text(encoding="utf-8")
    questions_js = (WEB_DIR / "questions.js").read_text(encoding="utf-8")

    # Escape </script> sequences inside inline JS safely
    safe_questions_js = questions_js.replace("</script>", "<\\/script>")
    inline_tag = f"<script>\n{safe_questions_js}\n  </script>"

    target = '<script src="questions.js"></script>'
    if target not in html:
        raise RuntimeError(f"Could not find {target!r} in web/index.html")

    bundled_html = html.replace(target, inline_tag, 1)

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    ts_content = (
        "// Auto-generated by scripts/bundle_html.py — do not edit manually.\n"
        f"export const INTERVIEW_APP_HTML: string = {json.dumps(bundled_html, ensure_ascii=False)};\n"
    )
    OUT_PATH.write_text(ts_content, encoding="utf-8")
    print(f"Bundled {len(bundled_html):,} characters into {OUT_PATH}")


if __name__ == "__main__":
    main()
