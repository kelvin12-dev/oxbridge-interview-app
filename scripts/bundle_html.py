#!/usr/bin/env python3
"""
Bundle web/index.html and web/data_presets.js into:
1. ios-native/Resources/index.html (self-contained HTML for native iOS WKWebView)
2. src/htmlBundle.ts (self-contained TypeScript module for React Native / Expo)
"""

import json
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
WEB_DIR = BASE_DIR / "web"
IOS_OUT_PATH = BASE_DIR / "ios-native" / "Resources" / "index.html"
TS_OUT_PATH = BASE_DIR / "src" / "htmlBundle.ts"


def main() -> None:
    html = (WEB_DIR / "index.html").read_text(encoding="utf-8")
    presets_js = (WEB_DIR / "data_presets.js").read_text(encoding="utf-8")

    safe_presets_js = presets_js.replace("</script>", "<\\/script>")
    inline_tag = f"<script>\n{safe_presets_js}\n  </script>"

    target = '<script src="data_presets.js"></script>'
    if target not in html:
        raise RuntimeError(f"Could not find {target!r} in web/index.html")

    bundled_html = html.replace(target, inline_tag, 1)

    IOS_OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    IOS_OUT_PATH.write_text(bundled_html, encoding="utf-8")
    print(f"Wrote {len(bundled_html):,} characters to {IOS_OUT_PATH}")

    TS_OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    ts_content = (
        "// Auto-generated by scripts/bundle_html.py — do not edit manually.\n"
        f"export const GOODNOTES_PRO_HTML: string = {json.dumps(bundled_html, ensure_ascii=False)};\n"
    )
    TS_OUT_PATH.write_text(ts_content, encoding="utf-8")
    print(f"Bundled {len(bundled_html):,} characters into {TS_OUT_PATH}")


if __name__ == "__main__":
    main()
